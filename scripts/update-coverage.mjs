// Regenerate the "Local News Coverage" list in sources.html from
// data/local-stations.json, so the public list can't drift from the data the
// app actually uses. Run after adding cities:  npm run coverage
//
// The list is written into the committed HTML (not rendered client-side) so
// crawlers see the city names — this page is the site's main organic hook for
// "<city> local news".
import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const DATA = path.join(repoRoot, "data", "local-stations.json");
const PAGE = path.join(repoRoot, "sources.html");
const START = "<!-- coverage:start — generated by scripts/update-coverage.mjs; do not edit by hand -->";
const END = "<!-- coverage:end -->";

const STATE_NAMES = {
  AL: "Alabama", AK: "Alaska", AZ: "Arizona", AR: "Arkansas", CA: "California",
  CO: "Colorado", CT: "Connecticut", DE: "Delaware", DC: "Washington, D.C.",
  FL: "Florida", GA: "Georgia", HI: "Hawaii", ID: "Idaho", IL: "Illinois",
  IN: "Indiana", IA: "Iowa", KS: "Kansas", KY: "Kentucky", LA: "Louisiana",
  ME: "Maine", MD: "Maryland", MA: "Massachusetts", MI: "Michigan",
  MN: "Minnesota", MS: "Mississippi", MO: "Missouri", MT: "Montana",
  NE: "Nebraska", NV: "Nevada", NH: "New Hampshire", NJ: "New Jersey",
  NM: "New Mexico", NY: "New York", NC: "North Carolina", ND: "North Dakota",
  OH: "Ohio", OK: "Oklahoma", OR: "Oregon", PA: "Pennsylvania",
  RI: "Rhode Island", SC: "South Carolina", SD: "South Dakota", TN: "Tennessee",
  TX: "Texas", UT: "Utah", VT: "Vermont", VA: "Virginia", WA: "Washington",
  WV: "West Virginia", WI: "Wisconsin", WY: "Wyoming",
};

const escapeHtml = s => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
// "st. louis" -> "St. Louis"; matches getNearestCities' displayCity rule.
const titleCase = s => s.replace(/\b\w/g, c => c.toUpperCase());

const { states } = JSON.parse(await fs.readFile(DATA, "utf8"));

let cityCount = 0;
let feedCount = 0;
const items = [];

for (const abbr of Object.keys(states).sort((a, b) => (STATE_NAMES[a] || a).localeCompare(STATE_NAMES[b] || b))) {
  const block = states[abbr];
  const cities = Object.keys(block).filter(k => k !== "_state").sort();
  for (const key of Object.keys(block)) feedCount += (block[key].entries || []).length;
  cityCount += cities.length;

  const label = escapeHtml(STATE_NAMES[abbr] || abbr);
  const detail = cities.length
    ? escapeHtml(cities.map(titleCase).join(", "))
    : "Statewide sources";
  items.push(`        <li><span class="coverageState">${label}</span>${detail}</li>`);
}

const stateCount = Object.keys(states).filter(a => a !== "DC").length;
const summary = `      <p class="hint coverageSummary">${cityCount} cities across ${stateCount} states and Washington, D.C. — ${feedCount} verified feeds.</p>`;

const generated = [START, summary, '      <ul class="coverageList">', ...items, "      </ul>", `      ${END}`].join("\n");

const html = await fs.readFile(PAGE, "utf8");
const startIdx = html.indexOf(START);
const endIdx = html.indexOf(END);
if (startIdx === -1 || endIdx === -1) {
  console.error("Coverage markers not found in sources.html — nothing written.");
  process.exit(1);
}

const updated = html.slice(0, startIdx) + generated + html.slice(endIdx + END.length);
if (updated === html) {
  console.log("Coverage list already up to date.");
} else {
  await fs.writeFile(PAGE, updated, "utf8");
  console.log(`Coverage list updated: ${cityCount} cities, ${stateCount} states + DC, ${feedCount} feeds.`);
}
